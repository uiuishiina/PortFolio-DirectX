#pragma once

///====================================================================
/// to_index 列挙体補助関数
///====================================================================

/*
	列挙体中での特定要素のインデックスを取得できる関数\
	列挙体を配列として扱いたい場合に使用
*/

//@brief	=== 列挙体インデックス番号変換取得関数 ===
template<class Enum>
constexpr size_t to_index(Enum e) noexcept {
	return static_cast<size_t>(e);
}